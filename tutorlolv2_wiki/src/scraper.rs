use {
    crate::{HTTP_CLIENT, JsonRead, MOBALYTICS_ENDPOINT, MayFail, selector},
    heck::ToPascalCase,
    rayon::iter::{IntoParallelIterator, ParallelIterator},
    reqwest::header::ACCEPT,
    scraper::{ElementRef, Html, Selector},
    serde::{Deserialize, de::IgnoredAny},
    std::{
        collections::{BTreeMap, BTreeSet},
        path::{Path, PathBuf},
    },
    tokio::task::JoinSet,
    tutorlolv2_types::Position,
};

fn cache() -> PathBuf {
    PathBuf::from("cache/scraper")
}

const POSITIONS: [Position; 5] = [
    Position::Top,
    Position::Jungle,
    Position::Middle,
    Position::Bottom,
    Position::Support,
];

/// Recommended `[items, runes]` for each position of each champion, in the
/// format that the build script expects from `internal/scraper/data.json`
pub type Recommendations = BTreeMap<String, BTreeMap<&'static str, [BTreeSet<String>; 2]>>;

fn champion_ids() -> MayFail<Vec<String>> {
    Ok(
        BTreeMap::<String, IgnoredAny>::from_file("cache/wiki/champions/full.json")?
            .into_keys()
            .collect(),
    )
}

fn page_path(champion_id: &str, position: Position) -> PathBuf {
    cache()
        .join(champion_id)
        .join(position.role())
        .with_extension("html")
}

/// Downloads the page and saves it to `save_to`, unless it is already cached.
/// Error statuses and challenge pages are rejected so they never get cached
async fn fetch(url: &str, save_to: &Path) -> MayFail {
    if let Ok(true) = std::fs::exists(save_to) {
        println!("[exists] {save_to:?}");
        return Ok(());
    }

    let text = HTTP_CLIENT
        .get(url)
        .header(ACCEPT, "text/html,application/xhtml+xml")
        .send()
        .await?
        .error_for_status()?
        .text()
        .await?;

    if text.contains("<title>Just a moment") {
        return Err(format!("[fetch] Blocked by a challenge page: {url}").into());
    }

    println!("[fetch] {url} -> {save_to:?}");
    crate::write(save_to, text)
}

/// Downloads the build page of every champion, one champion at a time, and
/// all positions of that champion concurrently
pub async fn download() -> MayFail {
    println!("[fn] scraper::download");

    for champion_id in champion_ids()? {
        let slug = champion_id.to_lowercase();
        let mut tasks = JoinSet::new();

        for position in POSITIONS {
            let url = format!("{MOBALYTICS_ENDPOINT}/{slug}/build/{}", position.role());
            let save_to = page_path(&champion_id, position);

            tasks.spawn(async move { fetch(&url, &save_to).await });
        }

        while let Some(result) = tasks.join_next().await {
            match result {
                Ok(Ok(())) => {}
                Ok(Err(e)) => println!("[error] scraper::download {champion_id}: {e:?}"),
                Err(e) => println!("[error] Joining future for {champion_id}: {e:?}"),
            }
        }
    }

    Ok(())
}

/// Maps the riot ids found in the scraped pages to the enum variant names
/// generated by the build script
#[derive(Default)]
struct Catalog {
    by_id: BTreeMap<u32, String>,
    keys: BTreeSet<String>,
}

impl Catalog {
    fn insert(&mut self, key: String, riot_id: u32, custom: bool) {
        // Riot ids may be shared between a base game item and custom ones,
        // in which case the base game item takes precedence
        match self.by_id.get(&riot_id) {
            Some(_) if custom => {}
            _ => {
                self.by_id.insert(riot_id, key.clone());
            }
        }

        self.keys.insert(key);
    }

    fn items() -> MayFail<Self> {
        #[derive(Deserialize)]
        struct Data {
            id: u32,
            custom: bool,
        }

        #[derive(Deserialize)]
        struct Item {
            data: Data,
        }

        let mut catalog = Self::default();

        for (key, item) in BTreeMap::<String, Item>::from_file("internal/items.json")? {
            catalog.insert(key, item.data.id, item.data.custom);
        }

        Ok(catalog)
    }

    fn runes() -> MayFail<Self> {
        #[derive(Deserialize)]
        struct Data {
            custom: bool,
        }

        #[derive(Deserialize)]
        struct Rune {
            riot_id: u32,
            data: Data,
        }

        let mut catalog = Self::default();

        for (key, rune) in BTreeMap::<String, Rune>::from_file("internal/runes.json")? {
            catalog.insert(key, rune.riot_id, rune.data.custom);
        }

        Ok(catalog)
    }

    /// Resolves an `<img>` by the riot id in its `src`, falling back to its
    /// `alt` text, which is necessary for stat shards since their ids differ
    fn resolve(&self, img: ElementRef) -> Option<String> {
        let riot_id = img
            .attr("src")?
            .rsplit('/')
            .next()?
            .split('.')
            .next()?
            .parse::<u32>()
            .ok();

        if let Some(key) = riot_id.and_then(|id| self.by_id.get(&id)) {
            return Some(key.clone());
        }

        let alt = img.attr("alt")?.to_pascal_case();
        self.keys.contains(&alt).then_some(alt)
    }
}

/// Selects every `<img>` of the sections whose first heading matches `title`
fn section_images<'a>(
    html: &'a Html,
    sections: &'static Selector,
    title: &'static str,
) -> impl Iterator<Item = ElementRef<'a>> {
    html.select(sections)
        .filter(move |section| {
            section
                .select(selector!("h3, h4"))
                .next()
                .is_some_and(|h| h.text().collect::<String>().trim().eq_ignore_ascii_case(title))
        })
        .flat_map(|section| section.select(selector!("img")))
}

fn parse_page(
    champion_id: &str,
    position: Position,
    html: &Html,
    items: &Catalog,
    runes: &Catalog,
) -> [BTreeSet<String>; 2] {
    let collect = |catalog: &Catalog, images: &mut dyn Iterator<Item = ElementRef>| {
        images
            .filter_map(|img| {
                let key = catalog.resolve(img);

                if key.is_none() {
                    println!(
                        "[warn] {champion_id} {position}: Unknown {:?} ({:?})",
                        img.attr("alt").unwrap_or_default(),
                        img.attr("src").unwrap_or_default(),
                    );
                }

                key
            })
            .collect::<BTreeSet<_>>()
    };

    let item_set = collect(
        items,
        &mut section_images(html, selector!("div.m-8atqhb"), "Full Build").chain(
            section_images(html, selector!("div.m-byg1ps"), "Situational Items"),
        ),
    );

    // Selected keystone, selected minor runes and selected stat shards
    let rune_set = collect(
        runes,
        &mut html.select(selector!("img.m-ylhwma, img.m-1ddfn83, img.m-1u3ui07")),
    );

    [item_set, rune_set]
}

/// Parses every downloaded page and aggregates the recommended items and
/// runes into `internal/scraper/data.json`
pub fn parse() -> MayFail {
    println!("[fn] scraper::parse");

    let items = Catalog::items()?;
    let runes = Catalog::runes()?;

    let recommendations = champion_ids()?
        .into_par_iter()
        .filter_map(|champion_id| {
            let positions = POSITIONS
                .into_iter()
                .filter_map(|position| {
                    let data = crate::read_to_string(page_path(&champion_id, position)).ok()?;
                    let html = Html::parse_document(&data);
                    let result = parse_page(&champion_id, position, &html, &items, &runes);

                    if result.iter().all(BTreeSet::is_empty) {
                        println!("[warn] {champion_id} {position}: No recommendations found");
                        return None;
                    }

                    Some((position.role(), result))
                })
                .collect::<BTreeMap<_, _>>();

            (!positions.is_empty()).then_some((champion_id, positions))
        })
        .collect::<Recommendations>();

    let json = serde_json::to_string_pretty(&recommendations)?;
    crate::write("internal/scraper/data.json", &json)
}

pub async fn run() -> MayFail {
    download().await?;
    parse()
}
